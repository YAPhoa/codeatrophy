-- The schema at logical version 5: everything SQLite migrations 0001 to
-- 0005 build, in one migration. Later schema changes are one migration each,
-- numbered like their SQLite counterpart.
--
-- Physical types differ from SQLite where PostgreSQL needs it, with the same
-- tables, columns and rules:
--
-- - Text that is only ever ordered or compared byte-wise uses the "C"
--   collation, like SQLite's default BINARY collation.
-- - Free text without a control-character rule (bodies, notes, source code,
--   program input and output) is bytea: PostgreSQL text cannot hold the NUL
--   character, and program output need not be valid UTF-8. The store
--   converts to and from Go strings.
-- - Flags are booleans; timestamps are Unix seconds, as in SQLite.
-- - Rules that SQLite enforces with triggers are CHECK constraints where a
--   constraint can express them, triggers otherwise.
-- - Foreign keys are DEFERRABLE (initially immediate) so that copying a
--   whole database in can check them at the end.

-- Number of UTF-8 characters in b, for length rules on bytea columns.
CREATE FUNCTION codeatrophy_utf8_length(b bytea) RETURNS integer
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$ SELECT count(*)::integer FROM generate_series(0, length(b) - 1) AS i WHERE get_byte(b, i) & 192 <> 128 $$;

-- True when s has no newline, carriage return or tab.
CREATE FUNCTION codeatrophy_single_line(s text) RETURNS boolean
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$ SELECT strpos(s, chr(10)) = 0 AND strpos(s, chr(9)) = 0 AND strpos(s, chr(13)) = 0 $$;

-- Raises the trigger's first argument as an error.
CREATE FUNCTION codeatrophy_reject() RETURNS trigger
LANGUAGE plpgsql
AS $$ BEGIN RAISE EXCEPTION '%', TG_ARGV[0]; END $$;

CREATE TABLE items (
    seq             bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id              text    COLLATE "C" NOT NULL UNIQUE,
    type            text    COLLATE "C" NOT NULL,
    title           text    COLLATE "C" NOT NULL,
    summary         bytea   NOT NULL DEFAULT '',
    body            bytea   NOT NULL DEFAULT '',
    difficulty      text    COLLATE "C",
    status          text    COLLATE "C" NOT NULL,
    favorite        boolean NOT NULL DEFAULT false,
    notes           bytea   NOT NULL DEFAULT '',
    raw_input       bytea,
    source_url      text    COLLATE "C",
    source_note     bytea,
    variant_of      text    COLLATE "C" REFERENCES items (id) ON DELETE SET NULL DEFERRABLE,
    revision        bigint  NOT NULL DEFAULT 1,
    time_limit_ms   bigint,
    memory_limit_kb bigint,
    compare_mode    text    COLLATE "C",
    starter_code    text    COLLATE "C",
    created_at      bigint  NOT NULL,
    updated_at      bigint  NOT NULL
);

CREATE INDEX items_variant_of ON items (variant_of);
CREATE INDEX items_updated_at ON items (updated_at);
CREATE INDEX items_created_at ON items (created_at);

CREATE TABLE item_tags (
    item_id text COLLATE "C" NOT NULL REFERENCES items (id) ON DELETE CASCADE DEFERRABLE,
    tag     text COLLATE "C" NOT NULL,
    PRIMARY KEY (item_id, tag)
);

CREATE INDEX item_tags_tag ON item_tags (tag);

CREATE TABLE test_cases (
    seq             bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id              text    COLLATE "C" NOT NULL UNIQUE,
    item_id         text    COLLATE "C" NOT NULL REFERENCES items (id) ON DELETE CASCADE DEFERRABLE,
    position        bigint  NOT NULL,
    name            bytea   NOT NULL DEFAULT '',
    stdin           bytea   NOT NULL DEFAULT '',
    expected_stdout bytea   NOT NULL DEFAULT '',
    is_sample       boolean NOT NULL DEFAULT false,
    origin          text    COLLATE "C" NOT NULL,
    verified        boolean NOT NULL DEFAULT false,
    created_at      bigint  NOT NULL,
    updated_at      bigint  NOT NULL
);

CREATE INDEX test_cases_item ON test_cases (item_id, position);

CREATE TABLE collections (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id          text   COLLATE "C" NOT NULL UNIQUE,
    name        text   COLLATE "C" NOT NULL,
    description bytea  NOT NULL DEFAULT '',
    parent_id   text   COLLATE "C" REFERENCES collections (id) ON DELETE SET NULL DEFERRABLE,
    position    bigint NOT NULL,
    created_at  bigint NOT NULL,
    updated_at  bigint NOT NULL
);

CREATE INDEX collections_parent ON collections (parent_id, position);

CREATE TABLE collection_items (
    collection_id text   COLLATE "C" NOT NULL REFERENCES collections (id) ON DELETE CASCADE DEFERRABLE,
    item_id       text   COLLATE "C" NOT NULL REFERENCES items (id) ON DELETE CASCADE DEFERRABLE,
    position      bigint NOT NULL,
    PRIMARY KEY (collection_id, item_id)
);

CREATE INDEX collection_items_item ON collection_items (item_id);

CREATE TABLE submissions (
    seq            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id             text   COLLATE "C" NOT NULL UNIQUE,
    item_id        text   COLLATE "C" NOT NULL REFERENCES items (id) ON DELETE CASCADE DEFERRABLE,
    mode           text   COLLATE "C" NOT NULL,
    language       text   COLLATE "C" NOT NULL,
    source         bytea  NOT NULL,
    stdin          bytea,
    case_ids       text   COLLATE "C" NOT NULL DEFAULT '[]',
    status         text   COLLATE "C" NOT NULL,
    verdict        text   COLLATE "C",
    passed_count   bigint NOT NULL DEFAULT 0,
    total_count    bigint NOT NULL DEFAULT 0,
    time_ms        bigint,
    memory_kb      bigint,
    compile_output bytea  NOT NULL DEFAULT '',
    error          bytea,
    created_at     bigint NOT NULL,
    finished_at    bigint
);

CREATE INDEX submissions_item ON submissions (item_id, seq);
CREATE INDEX submissions_status ON submissions (status);

CREATE TABLE submission_results (
    submission_id   text    COLLATE "C" NOT NULL REFERENCES submissions (id) ON DELETE CASCADE DEFERRABLE,
    idx             bigint  NOT NULL,
    test_case_id    text    COLLATE "C",
    name            bytea   NOT NULL DEFAULT '',
    is_sample       boolean NOT NULL DEFAULT false,
    verdict         text    COLLATE "C" NOT NULL,
    stdin           bytea   NOT NULL DEFAULT '',
    expected_stdout bytea,
    stdout          bytea   NOT NULL DEFAULT '',
    stderr          bytea   NOT NULL DEFAULT '',
    time_ms         bigint,
    memory_kb       bigint,
    PRIMARY KEY (submission_id, idx)
);

CREATE TABLE settings (
    key   text COLLATE "C" PRIMARY KEY,
    value text COLLATE "C" NOT NULL
);

-- Search index over item content, maintained by the store on every item
-- write: each column holds the text's tokens (folded to lower case, without
-- diacritics), separated by single spaces and enclosed in spaces.
CREATE TABLE items_search (
    seq     bigint PRIMARY KEY REFERENCES items (seq) ON DELETE CASCADE,
    title   text COLLATE "C" NOT NULL,
    summary text COLLATE "C" NOT NULL,
    body    text COLLATE "C" NOT NULL,
    tags    text COLLATE "C" NOT NULL
);

-- Style presets: the user's named writing instructions. The application
-- enforces the full limits; these constraints back them up.
CREATE TABLE style_presets (
    seq          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id           text    COLLATE "C" NOT NULL UNIQUE,
    name         text    COLLATE "C" NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
    name_key     text    COLLATE "C" NOT NULL UNIQUE,
    instructions text    COLLATE "C" NOT NULL CHECK (char_length(instructions) BETWEEN 1 AND 2000),
    is_default   boolean NOT NULL DEFAULT false,
    created_at   bigint  NOT NULL,
    updated_at   bigint  NOT NULL,
    CONSTRAINT style_presets_name_single_line CHECK (codeatrophy_single_line(name))
);

-- At most one default preset.
CREATE UNIQUE INDEX style_presets_single_default ON style_presets (is_default) WHERE is_default;

-- Saved solutions. A problem keeps any number of them; at most one is the
-- reference solution.
CREATE TABLE solutions (
    seq          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id           text    COLLATE "C" NOT NULL UNIQUE,
    item_id      text    COLLATE "C" NOT NULL REFERENCES items (id) ON DELETE CASCADE DEFERRABLE,
    name         text    COLLATE "C" NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
    language     text    COLLATE "C" NOT NULL,
    source       bytea   NOT NULL CHECK (length(source) > 0),
    notes        bytea   NOT NULL DEFAULT '' CHECK (length(notes) <= 5000 OR codeatrophy_utf8_length(notes) <= 5000),
    is_reference boolean NOT NULL DEFAULT false,
    created_at   bigint  NOT NULL,
    updated_at   bigint  NOT NULL,
    CONSTRAINT solutions_name_single_line CHECK (codeatrophy_single_line(name))
);

CREATE INDEX solutions_item ON solutions (item_id, seq);

-- At most one reference solution per item.
CREATE UNIQUE INDEX solutions_single_reference ON solutions (item_id) WHERE is_reference;

-- Saved AI providers: named connections to an AI service, each with its own
-- kind, model, base URL and API key. Empty model and base URL mean the
-- kind's default. api_key is ciphertext bound to (kind, api_key_origin); it
-- is empty when no key is stored.
CREATE TABLE ai_providers (
    seq            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id             text   COLLATE "C" NOT NULL UNIQUE,
    name           text   COLLATE "C" NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
    name_key       text   COLLATE "C" NOT NULL UNIQUE,
    kind           text   COLLATE "C" NOT NULL CHECK (kind IN ('anthropic', 'openai_compatible')),
    model          text   COLLATE "C" NOT NULL DEFAULT '',
    base_url       text   COLLATE "C" NOT NULL DEFAULT '',
    api_key        text   COLLATE "C" NOT NULL DEFAULT '',
    api_key_origin text   COLLATE "C" NOT NULL DEFAULT '',
    created_at     bigint NOT NULL,
    updated_at     bigint NOT NULL,
    CONSTRAINT ai_providers_name_single_line CHECK (codeatrophy_single_line(name))
);

-- The kind is fixed at creation.
CREATE TRIGGER ai_providers_kind_immutable BEFORE UPDATE OF kind ON ai_providers
FOR EACH ROW WHEN (NEW.kind IS DISTINCT FROM OLD.kind)
EXECUTE FUNCTION codeatrophy_reject('the kind of an AI provider cannot be changed');

-- Count limits: at most 20 presets, 20 providers and 50 solutions per item.
-- Writers are serialised by the store, so a count read in a trigger cannot
-- be overtaken by a concurrent insert.
CREATE FUNCTION codeatrophy_check_count() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    n bigint;
BEGIN
    IF TG_TABLE_NAME = 'style_presets' THEN
        SELECT count(*) INTO n FROM style_presets;
        IF n >= 20 THEN RAISE EXCEPTION 'too many style presets'; END IF;
    ELSIF TG_TABLE_NAME = 'ai_providers' THEN
        SELECT count(*) INTO n FROM ai_providers;
        IF n >= 20 THEN RAISE EXCEPTION 'too many AI providers'; END IF;
    ELSIF TG_TABLE_NAME = 'solutions' THEN
        SELECT count(*) INTO n FROM solutions WHERE item_id = NEW.item_id;
        IF n >= 50 THEN RAISE EXCEPTION 'too many solutions for this item'; END IF;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER style_presets_max_count BEFORE INSERT ON style_presets
FOR EACH ROW EXECUTE FUNCTION codeatrophy_check_count();
CREATE TRIGGER ai_providers_max_count BEFORE INSERT ON ai_providers
FOR EACH ROW EXECUTE FUNCTION codeatrophy_check_count();
CREATE TRIGGER solutions_max_per_item BEFORE INSERT ON solutions
FOR EACH ROW EXECUTE FUNCTION codeatrophy_check_count();

-- Built-in style presets for a new instance, as SQLite migration 0005
-- seeds them: ordinary rows, fully editable and deletable, counted against
-- the limit of 20, seeded only into an empty table and only by this
-- migration, so a deleted seed never comes back.
INSERT INTO style_presets (id, name, name_key, instructions, is_default, created_at, updated_at)
SELECT gen_random_uuid()::text, name, lower(name), instructions, is_default,
       extract(epoch FROM now())::bigint, extract(epoch FROM now())::bigint
FROM (VALUES
    (1, 'Interview practice', true,
     'Write the statement the way an interviewer would pose it: two or three short paragraphs in plain language, with no back-story. Name the inputs and say exactly what to print. Give two or three small examples, each followed by one or two sentences explaining why that output is correct. Keep the constraints to a short list, chosen so that the intended time complexity matters. Under Notes, add a "Follow-up" line that asks for a better complexity or a harder twist without giving the approach away. Starter code in Python and Java.'),
    (2, 'Contest style', false,
     'Write in the style of a programming-contest problem: a short, concrete scenario of at most one paragraph, then a precise formal statement. Use math notation for every bound. Choose the limits so that the intended complexity is implied but never named. Give at least two examples and explain only the non-obvious one, under Notes. No hints. Starter code in C++ and Python.'),
    (3, 'Study notes', false,
     'Write for revision rather than for a test. For a reading: open with a two-sentence summary, then short sections with descriptive headings, each with a small worked example or code sample, and close with "Key takeaways" (three to five bullets) and "Check yourself" (three questions without answers). For a problem: keep the statement brief, and use Notes to name the underlying technique and point to related topics without giving the solution. Prefer plain words to jargon, and define each term the first time it appears.')
) AS seed (ord, name, is_default, instructions)
WHERE NOT EXISTS (SELECT 1 FROM style_presets)
ORDER BY ord;
