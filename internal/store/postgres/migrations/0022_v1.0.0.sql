    total_count    bigint NOT NULL DEFAULT 0,
    time_ms        bigint,
    memory_kb      bigint,
    compile_output bytea  NOT NULL DEFAULT '',
    error          bytea,
    created_at     bigint NOT NULL,
    finished_at    bigint,
    line_offset    bigint NOT NULL DEFAULT 0 CONSTRAINT submissions_line_offset CHECK (line_offset >= 0),
    harness        text   COLLATE "C",
    user_id        text   COLLATE "C" NOT NULL DEFAULT ''
);

CREATE INDEX submissions_item ON submissions (item_id, seq);
CREATE INDEX submissions_status ON submissions (status);
CREATE INDEX submissions_user_item ON submissions (user_id, item_id, seq);

CREATE TABLE submission_results (
