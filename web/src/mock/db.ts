export interface MockOptions {
  /** Whether an AI provider is configured at start. Default `true`. */
  ai?: boolean;
  /** `ok`: a healthy engine; `none`: no engine; `down`: configured but unreachable. */
  judge?: 'ok' | 'none' | 'down';
  /** `open`: enabled without a token; `token`: bearer token required; `off`: disabled. */
  mcp?: 'open' | 'token' | 'off';
  /** `seed`: a realistic library; `empty`: a brand-new instance. */
  library?: 'seed' | 'empty';
  /** `normal`: realistic latency; `fast`: short delays; `instant`: none at all. */
  speed?: 'normal' | 'fast' | 'instant';
  /** `seed`: the seed library's style presets; `none`: start with no presets. */
  styles?: 'seed' | 'none';
  /** Whether the operator configured a public URL, reported as `mcp.url`. Default `false`. */
  publicUrl?: boolean;
  /**
   * Where the Anthropic provider's model, base URL and key come from at
   * start: saved through the API, or supplied by the server's environment.
   */
  aiSource?: 'settings' | 'environment';
  /** Answer every state-changing request with `403 forbidden`, as for a foreign origin. */
  forbidden?: boolean;
}

export interface StoredItem {
  id: string;
  type: ItemType;
  title: string;
  summary: string;
  body: string;
  difficulty: Difficulty | null;
  tags: string[];
  status: ItemStatus;
  favorite: boolean;
  notes: string;
  rawInput: string | null;
  source: ItemSource;
  problem: ProblemSpec | null;
  variantOf: string | null;
  revision: number;
  createdAt: string;
  updatedAt: string;
  /** Monotonic counter that breaks ties between equal timestamps. */
  seq: number;
}

export interface StoredCollection {
  id: string;
  name: string;
  description: string;
  parentId: string | null;
  position: number;
  /** Ordered membership. */
  itemIds: string[];
  createdAt: string;
  updatedAt: string;
}

